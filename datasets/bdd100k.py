"""BDD100K three-task dataset (Detection + Drivable Area + Lane) for unified evaluation.

Reads the official BDD100K layout under data/bdd100k:
    images/100k/{train,val}/<name>.jpg
    labels/bdd100k_labels_images_{train,val}.json      (detection boxes, list format)
    segments/masks/{train,val}/<name>.png              (drivable area, values 0/1/2)
    lanes/masks/{train,val}/<name>.png                 (lane, multi-class values)

Split manifests live in data/bdd100k/splits/*.txt (generated by
scripts/verify_dataset.py). Each line is an image basename without extension.

YOLO-style letterbox: images, masks and boxes are all mapped into the same
img_size x img_size coordinate space; `meta` records (scale, pad) so results
can be mapped back to native coordinates if needed.

Detection GT follows the official baselines' protocol: category == 'car' only
(YOLOP and TriLiteNet official models are single-class, nc=1).
"""
import json
import os

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset


def letterbox(img, new_shape=(640, 640), color=(114, 114, 114)):
    """Resize+pad preserving aspect ratio (YOLO-style). Returns img, (scale, pad_w, pad_h)."""
    h, w = img.shape[:2]
    r = min(new_shape[0] / h, new_shape[1] / w)
    nh, nw = round(h * r), round(w * r)
    resized = cv2.resize(img, (nw, nh), interpolation=cv2.INTER_LINEAR)
    top = (new_shape[0] - nh) // 2
    bottom = new_shape[0] - nh - top
    left = (new_shape[1] - nw) // 2
    right = new_shape[1] - nw - left
    out = cv2.copyMakeBorder(resized, top, bottom, left, right,
                             cv2.BORDER_CONSTANT, value=color)
    return out, (r, left, top), (nh, nw)


class BDD100KDataset(Dataset):
    # YOLOP/TriLiteNet official models are single-class; the released weights
    # treat all vehicles (car/bus/truck/train) as one class (see YOLOP
    # lib/dataset/convert.py id_dict_single). "car" alone undercounts GT.
    DET_CATEGORIES = ("car", "bus", "truck", "train")

    def __init__(self, data_root, split="tri_val", img_size=640,
                 with_det=True, with_da=True, with_lane=True,
                 det_categories=DET_CATEGORIES):
        self.data_root = data_root
        self.split = split
        self.img_size = img_size
        self.with_det, self.with_da, self.with_lane = with_det, with_da, with_lane
        self.det_categories = set(det_categories)

        split_file = os.path.join(data_root, "splits", f"{split}.txt")
        with open(split_file) as f:
            self.names = [ln.strip() for ln in f if ln.strip()]

        self._det_labels = None
        if with_det:
            json_file = os.path.join(data_root, "labels",
                                     f"bdd100k_labels_images_{split.split('_')[-1]}.json")
            with open(json_file) as f:
                self._det_labels = json.load(f)
            self._det_by_name = {x["name"].rsplit(".", 1)[0]: x for x in self._det_labels}

    def __len__(self):
        return len(self.names)

    def _load_mask(self, kind, name):
        p = os.path.join(self.data_root, kind, "masks", self.split.split("_")[-1], f"{name}.png")
        m = cv2.imread(p, cv2.IMREAD_GRAYSCALE)
        if m is None:
            raise FileNotFoundError(p)
        if kind == "segments":
            # BDD100K drivable area: 0=background, 1=direct, 2=alternative -> fg = >0
            m = (m > 0).astype(np.uint8)
        else:
            # BDD100K lane: lane-type values (1-9 etc.) are foreground, 255 = background
            m = ((m > 0) & (m < 255)).astype(np.uint8)
        return m

    def __getitem__(self, idx):
        name = self.names[idx]
        img = cv2.imread(os.path.join(self.data_root, "images", "100k",
                                      self.split.split("_")[-1], f"{name}.jpg"))
        if img is None:
            raise FileNotFoundError(name)
        orig_shape = img.shape[:2]
        img, (scale, pad_w, pad_h), (nh, nw) = letterbox(img, (self.img_size, self.img_size))
        img = img[:, :, ::-1].transpose(2, 0, 1)  # BGR->RGB, HWC->CHW
        img = torch.from_numpy(np.ascontiguousarray(img)).float() / 255.0

        item = {
            "image": img, "name": name,
            "orig_shape": orig_shape, "scale": scale,
            "pad": (pad_w, pad_h), "content_size": (nh, nw),
        }

        if self.with_det:
            boxes = []
            labels = self._det_by_name.get(name, {"labels": []})["labels"]
            for lab in labels:
                cat = lab.get("category")
                box = lab.get("box2d")
                if cat in self.det_categories and box is not None:
                    x1, y1, x2, y2 = (float(box["x1"]), float(box["y1"]),
                                      float(box["x2"]), float(box["y2"]))
                    # to letterboxed coords
                    x1, x2 = x1 * scale + pad_w, x2 * scale + pad_w
                    y1, y2 = y1 * scale + pad_h, y2 * scale + pad_h
                    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
                    w, h = x2 - x1, y2 - y1
                    boxes.append([0, cx / self.img_size, cy / self.img_size,
                                  w / self.img_size, h / self.img_size])
            item["det_targets"] = torch.tensor(boxes, dtype=torch.float32) if boxes \
                else torch.zeros((0, 5), dtype=torch.float32)

        if self.with_da:
            m = self._load_mask("segments", name)
            m, _, _ = letterbox(m, (self.img_size, self.img_size), color=0)
            item["da_mask"] = torch.from_numpy(m.astype(np.float32)).unsqueeze(0)
        if self.with_lane:
            m = self._load_mask("lanes", name)
            m, _, _ = letterbox(m, (self.img_size, self.img_size), color=0)
            item["lane_mask"] = torch.from_numpy(m.astype(np.float32)).unsqueeze(0)
        return item


def collate(items):
    """Minimal collate: images stacked, other fields kept as lists."""
    out = {}
    for k in items[0]:
        if k == "image":
            out[k] = torch.stack([it[k] for it in items])
        else:
            out[k] = [it[k] for it in items]
    return out
