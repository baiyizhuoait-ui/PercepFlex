        ca, cb = cells[a], cells[b]
        if ca["params_M"] > cb["params_M"] + TOL:
            return False
        if ca["flops_G"] > cb["flops_G"] + TOL:
            return False
        return all(ca[m] >= cb[m] - TOL for m in METRICS)

