def f(v, nd=4):
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def sf(v, nd=4):
    return f"{v:+.{nd}f}" if isinstance(v, float) else str(v)


def compute_stopping_rule(cells):
    """Return (rule, evidence_lines)."""
    da_lane = ["da_mIoU", "da_fg", "lane_mIoU", "lane_fg"]
    ev = []

    def dz(e, m, z=128):
        return cells[(e, z)][m] - cells[(e, 16)][m]

    rev_lg = sum(abs(dz("elarge", m)) > NOISE[m] for m in da_lane)
    rev_sm = sum(abs(dz("esmall", m)) > NOISE[m] for m in da_lane)
    z_any = sum(abs(dz(e, m)) > NOISE[m] for e in ENCODERS for m in METRICS)
    ev.append(f"- DA/Lane metrics revived by z=128 at E-large: **{rev_lg}/4**")
    ev.append(f"- DA/Lane metrics revived by z=128 at E-small: **{rev_sm}/4**")
    ev.append(f"- any metric moved beyond the reference noise floor anywhere: **{z_any}/18**")

    if rev_lg >= 2 and rev_lg > rev_sm:
        return "A", ev
    if rev_lg == 0 and rev_sm == 0 and z_any <= 2:
        return "B", ev
    if z_any >= 6:
        return "C", ev
    return "D", ev


